def render_consent_footer():
    """Render a small footer link to review consent/legal docs."""
    st.divider()
    with st.expander("📋 Legal: Terms of Use & Privacy Policy"):
        tab_terms, tab_privacy = st.tabs(["Terms of Use", "Privacy Policy"])
        with tab_terms:
            st.markdown(TERMS_OF_USE)
        with tab_privacy:
            st.markdown(PRIVACY_POLICY)
        
        # Show current consent status
        st.markdown("---")
        st.markdown("**Your consent status:**")
        st.markdown(f"- Terms accepted: {'✅' if st.session_state.get('consent_terms') else '❌'}")
        st.markdown(f"- Privacy accepted: {'✅' if st.session_state.get('consent_privacy') else '❌'}")
        if st.session_state.get('consent_timestamp'):
            st.markdown(f"- Consent given: {st.session_state['consent_timestamp'][:19]}")

def _mark_consent_accepted():
    set_consent(True, True)
    st.session_state["_reset_scroll_after_consent"] = True


def reset_main_scroll_once():
    """Reset the main Streamlit viewport after leaving the consent gate."""
    st.iframe(
        srcdoc="""
        <script>
        (() => {
            const deadline = performance.now() + 1500;

            function reset() {
                const doc = window.parent.document;
                const main = doc.querySelector(
                    'section[data-testid="stMain"]'
                );

                if (main) {
                    main.scrollTop = 0;
                    main.scrollLeft = 0;
                }

                if (window.parent.scrollY !== 0) {
                    window.parent.scrollTo(0, 0);
                }

                if (performance.now() < deadline) {
                    window.requestAnimationFrame(reset);
                }
            }

            window.requestAnimationFrame(reset);
        })();
        </script>
        """,
        height=0,
    )