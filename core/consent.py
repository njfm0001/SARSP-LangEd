def is_consent_given() -> bool:
    """Check if user has accepted required consents."""
    return (
        st.session_state.get("consent_terms", False)
        and st.session_state.get("consent_privacy", False)
    )


def set_consent(terms: bool, privacy: bool):
    """Record consent decisions in session state."""
    st.session_state["consent_terms"] = terms
    st.session_state["consent_privacy"] = privacy
    st.session_state["consent_timestamp"] = datetime.now().isoformat()


